HELP_STEPS = {
    'admin': [('user', 'Класс'), ('document', 'Задания'), ('check', 'Отчёты')],
    'teacher': [('document', 'Задание'), ('clock', 'Нагрузка'), ('check', 'Публикация')],
    'student': [('clock', 'Время'), ('document', 'План'), ('check', 'Выполнение')],
}


class InstructionMixin:
    def menu(self, uid, prefix=''):
        return self.with_instructions(super().menu(uid, prefix))

    def plan(self, uid, offset=0, page=0):
        return self.with_instructions(super().plan(uid, offset, page))

    def profile(self, uid, prefix=''):
        return self.with_instructions(super().profile(uid, prefix))

    def with_instructions(self, messages):
        rows = messages[0]['attachments'][0]['payload']['buttons']
        if not any(item.get('payload') == 'guide' for row in rows for item in row):
            rows.append([button('Инструкции', 'guide')])
        return messages

    def _handle(self, uid, text):
        if text in ('guide', '/guide', 'help', '/help'):
            return self.instructions(uid)
        if text.startswith('guide:'):
            role, _, topic = text.split(':', 1)[1].partition(':')
            return self.instructions(uid, role, topic)
        return super()._handle(uid, text)

    def instructions(self, uid, role='', topic=''):
        member = self.store.member(uid)
        if member:
            if role != member['role']:
                topic = ''
            role = member['role']
        if role not in GUIDES:
            return card('Инструкции\n\nВыберите роль, чтобы посмотреть порядок работы.',
                        [[button(label.capitalize(), f'guide:{key}')] for key, label in ROLE_LABELS.items()] +
                        [[button('Главное меню', 'menu')]],
                        'ИНСТРУКЦИИ', 'Выберите роль', kind='help')
        role_label = ROLE_LABELS[role].capitalize()
        sections = GUIDES[role]
        if topic in sections:
            title, paragraphs, shortcut = sections[topic]
            body = f'<b>{escape(title)}</b>\n{escape(role_label)}\n\n' + '\n\n'.join(paragraphs)
            rows = [[button(*shortcut)]] if member else []
            rows.extend([[button('К разделам инструкции', f'guide:{role}')], [button('Главное меню', 'menu')]])
        else:
            title = 'Инструкции'
            body = f'<b>Инструкции</b>\n{escape(role_label)}\n\nВыберите раздел.'
            rows = [[button(section[0], f'guide:{role}:{key}')] for key, section in sections.items()]
            if not member:
                rows.append([button('Выбрать другую роль', 'guide')])
            rows.append([button('Главное меню', 'menu')])
        messages = card(body, rows, 'ИНСТРУКЦИИ', role_label if topic not in sections else title,
                        kind='help', help_steps=HELP_STEPS[role], role=role_label,
                        class_name=member['name'] if member else '')
        messages[0]['format'] = 'html'
        return messages
